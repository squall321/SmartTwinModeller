"""export_abaqus_inp_v2 — atomic, read-only Abaqus INP exporter (v2).

A richer version of ``export_mesh_for_fem`` that consumes the full set of
body annotations attached by the other ``fem_cae`` skills:

  * body._pd_material        → ``*MATERIAL`` + ``*ELASTIC`` + ``*DENSITY``
  * body._pd_bcs             → ``*BOUNDARY`` (fixed/pinned) and ``*DLOAD`` /
                               ``*DSLOAD`` (pressure/force/temperature)
  * body._pd_thermal_bcs     → ``*BOUNDARY`` (fixed_temp) / ``*DFLUX`` /
                               ``*FILM`` / ``*SRADIATE``
  * body._pd_contacts        → ``*SURFACE`` + ``*CONTACT PAIR``
  * body._pd_load_cases      → one ``*STEP`` per case
  * body._pd_modal           → ``*FREQUENCY`` inside a modal step
  * body._pd_mesh_refinement → recorded as a comment block (the actual
                               per-zone meshing is left to the solver's
                               adaptive remesher)

The geometric surface mesh is generated by the same triangulation pipeline
as ``export_mesh_for_fem`` — we import that module's helpers so the two
exporters stay in sync.

Read-only — the body is returned unchanged; only the filesystem is touched.

extras["mesh_stats"]:
    {"tris": int, "nodes": int, "path": str, "format": "inp_v2",
     "mesh_size_mm": float, "bc_cards": int, "contact_cards": int,
     "load_case_steps": int}
"""
